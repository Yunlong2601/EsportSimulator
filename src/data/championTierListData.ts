// 根据当前赛季周获取对应版本补丁配置
export function getMetaConfigForWeek(week: number): PatchMetaTierConfig {
  const normalizedWeek = Math.max(1, Math.min(26, week));
  const found = PATCH_TIER_CONFIGS.find(c => normalizedWeek >= c.seasonWeeks[0] && normalizedWeek <= c.seasonWeeks[1]);
  return found || PATCH_TIER_CONFIGS[0];
}

// 计算阵容中 drafted 核心英雄带来的版本羁绊总增益
export function calculateDraftedMetaSynergyBonus(
  draftedChampions: Record<string, string> | undefined,
  currentWeek: number
): {
  totalSynergyBonus: number; // e.g. 0.18 (+18%)
  draftedMetaCount: number;
  bonusSummary: string;
  matchedChampions: MetaChampionEntry[];
} {
  if (!draftedChampions || Object.keys(draftedChampions).length === 0) {
    return {
      totalSynergyBonus: 0,
      draftedMetaCount: 0,
      bonusSummary: '未配置版本BP核心英雄',
      matchedChampions: []
    };
  }

  const metaConfig = getMetaConfigForWeek(currentWeek);
  const matchedChampions: MetaChampionEntry[] = [];
  let totalBonus = 0;

  Object.entries(draftedChampions).forEach(([_role, champId]) => {
    const metaChamp = metaConfig.champions.find(c => c.id === champId);
    if (metaChamp) {
      matchedChampions.push(metaChamp);
      totalBonus += metaChamp.synergyBonus;
    }
  });

  const draftedMetaCount = matchedChampions.length;
  let bonusSummary = `已契合 ${draftedMetaCount} 位版本强势英雄，获得 +${Math.round(totalBonus * 100)}% 战术羁绊总加成`;
  if (draftedMetaCount >= 4) {
    bonusSummary = `🔥【T0版本之子豪华阵容】${draftedMetaCount}位强势英雄联动！获得 +${Math.round(totalBonus * 100)}% 顶级BP压制与团战羁绊！`;
  } else if (draftedMetaCount === 0) {
    bonusSummary = '当前首发阵容偏离本版本梯队强势英雄，建议教练组根据当前版本调整BP';
  }

  return {
    totalSynergyBonus: totalBonus,
    draftedMetaCount,
    bonusSummary,
    matchedChampions
  };
}
